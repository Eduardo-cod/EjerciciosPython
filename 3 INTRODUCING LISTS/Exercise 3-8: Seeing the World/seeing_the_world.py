visit_places = ['canada', 'japan', 'italy', 'australia', 'brazil']

print("Original list:")
print(visit_places)

print("\nHere is the sorted list:")
print(sorted(visit_places))

print("\nHere is the original list:")
print(visit_places)

print("\nHere is the reversed list:")
visit_places.reverse()
print(visit_places)

print("\nHere is the reversed list again:")
visit_places.reverse()
print(visit_places)

print("\nHere is the sorted list:")
visit_places.sort()
print(visit_places)

print("\nHere is the sorted list in reverse alphabetical order:")
visit_places.sort(reverse=True)
print(visit_places)